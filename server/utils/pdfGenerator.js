const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

const formatReportTypeName = (type) => {
  switch (type) {
    case 'WEEKLY': return 'Weekly Compliance Report';
    case 'DAILY_WATER_QUALITY': return 'Daily Water Quality Report';
    case 'EQUIPMENT_HEALTH': return 'Equipment Health Report';
    case 'CHEMICAL_USAGE': return 'Chemical Usage Report';
    case 'PLANT_OPERATIONS': return 'Plant Operations Summary';
    case 'MONTHLY': return 'Monthly Audit Report';
    default: return type || 'Compliance & Regulatory Report';
  }
};

const generateCompliancePDF = (reportData, outputPath) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 50, autoFirstPage: true });
      const dir = path.dirname(outputPath);
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }

      const stream = fs.createWriteStream(outputPath);
      doc.pipe(stream);

      const drawHeaderBanner = () => {
        // Top academic prototype disclaimer bar
        doc.rect(50, 40, 512, 18).fill('#eff6ff');
        doc.fillColor('#1e40af').fontSize(8).font('Helvetica-Bold')
           .text('ACADEMIC PROTOTYPE DEMONSTRATION — SIMULATED COMPLIANCE & OPERATIONAL TELEMETRY DATA', 55, 45, { width: 502, align: 'center' });
      };

      const checkPageBreak = (neededHeight = 60) => {
        if (doc.y + neededHeight > 710) {
          doc.addPage();
          drawHeaderBanner();
          doc.y = 70;
        }
      };

      drawHeaderBanner();
      doc.y = 70;

      // Title Section
      doc.fillColor('#0f172a').fontSize(18).font('Helvetica-Bold').text('AQUA-OPTIMA AI WATER TREATMENT SYSTEM', { align: 'center' });
      doc.fillColor('#2563eb').fontSize(12).font('Helvetica-Bold').text(formatReportTypeName(reportData.reportType).toUpperCase(), { align: 'center' });
      doc.moveDown(1);

      // Metadata Block Box
      const metaY = doc.y;
      doc.rect(50, metaY, 512, 65).fill('#f8fafc').stroke('#cbd5e1');
      doc.fillColor('#1e293b').fontSize(9);

      doc.font('Helvetica-Bold').text('Facility Name:', 60, metaY + 10);
      doc.font('Helvetica').text(reportData.plantName || 'Central Water Treatment Plant', 145, metaY + 10);

      doc.font('Helvetica-Bold').text('Report Type:', 60, metaY + 26);
      doc.font('Helvetica').text(formatReportTypeName(reportData.reportType), 145, metaY + 26);

      doc.font('Helvetica-Bold').text('Evaluation Window:', 60, metaY + 42);
      doc.font('Helvetica').text(`${new Date(reportData.periodStart).toLocaleDateString()} - ${new Date(reportData.periodEnd).toLocaleDateString()}`, 165, metaY + 42);

      doc.font('Helvetica-Bold').text('Generated By:', 315, metaY + 10);
      doc.font('Helvetica').text(reportData.generatedByName || 'System Operator', 395, metaY + 10);

      doc.font('Helvetica-Bold').text('Generated Date:', 315, metaY + 26);
      doc.font('Helvetica').text(new Date().toLocaleString(), 395, metaY + 26);

      doc.font('Helvetica-Bold').text('Compliance Status:', 315, metaY + 42);
      doc.font('Helvetica-Bold').fillColor('#059669').text('MEETS STANDARDS (SIMULATED)', 410, metaY + 42);

      doc.y = metaY + 75;

      // 1. Executive Summary
      checkPageBreak(80);
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('1. Executive Operational Summary');
      doc.moveDown(0.3);
      doc.fillColor('#334155').fontSize(9).font('Helvetica').text(
        `This automated regulatory compliance report details the operational performance, water quality telemetry, chemical dosing efficiency, and equipment health metrics for ${reportData.plantName || 'Central Water Treatment Plant'}. During this evaluation window, plant operations achieved a 98.4% overall compliance baseline adhering to EPA and WHO drinking water quality standards. AI chemical optimization models successfully maintained ideal residual disinfectant concentrations while providing verified reagent cost efficiency.`
      );
      doc.moveDown(1);

      // 2. Water Quality Monitoring & Telemetry
      checkPageBreak(130);
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('2. Water Quality Telemetry & Sensor Statistics');
      doc.moveDown(0.3);

      const stats = reportData.stats || {};
      const sensorTableY = doc.y;
      doc.rect(50, sensorTableY, 512, 18).fill('#1e293b');
      doc.fillColor('#ffffff').fontSize(8.5).font('Helvetica-Bold');
      doc.text('Parameter', 60, sensorTableY + 5);
      doc.text('Measured Average', 165, sensorTableY + 5);
      doc.text('Target Operational Range', 285, sensorTableY + 5);
      doc.text('Regulatory Status', 445, sensorTableY + 5);

      const rows = [
        { param: 'pH Level', avg: `${stats.phAvg || '7.35'}`, range: '6.5 - 8.5 pH', status: 'COMPLIANT' },
        { param: 'Turbidity', avg: `${stats.turbidityAvg || '1.45'} NTU`, range: '< 5.0 NTU (Target < 1.0)', status: 'OPTIMAL' },
        { param: 'Residual Chlorine', avg: `${stats.chlorineAvg || '1.62'} mg/L`, range: '1.0 - 2.5 mg/L', status: 'COMPLIANT' },
        { param: 'Flow Rate', avg: `${stats.flowAvg || '124'} GPM`, range: '100 - 150 GPM', status: 'NORMAL' },
        { param: 'Line Pressure', avg: `${stats.pressureAvg || '45.2'} PSI`, range: '40 - 60 PSI', status: 'NORMAL' },
        { param: 'Water Quality Index Score', avg: `${stats.qualityScore || '92'} / 100`, range: '>= 85 Index Score', status: 'EXCELLENT' }
      ];

      let rY = sensorTableY + 18;
      rows.forEach((row, i) => {
        doc.rect(50, rY, 512, 18).fill(i % 2 === 0 ? '#f8fafc' : '#ffffff');
        doc.fillColor('#1e293b').fontSize(8.5).font('Helvetica');
        doc.text(row.param, 60, rY + 5);
        doc.text(row.avg, 165, rY + 5);
        doc.text(row.range, 285, rY + 5);
        doc.fillColor('#059669').font('Helvetica-Bold').text(row.status, 445, rY + 5);
        rY += 18;
      });

      doc.y = rY + 12;

      // 3. Equipment Health & Predictive Maintenance Overview
      checkPageBreak(140);
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('3. Equipment Fleet Health & Predictive Maintenance');
      doc.moveDown(0.3);

      const equipments = reportData.equipments || [];
      const eqTableY = doc.y;
      doc.rect(50, eqTableY, 512, 18).fill('#1e293b');
      doc.fillColor('#ffffff').fontSize(8.5).font('Helvetica-Bold');
      doc.text('Equipment Name', 60, eqTableY + 5);
      doc.text('Type', 195, eqTableY + 5);
      doc.text('Health Score', 275, eqTableY + 5);
      doc.text('Telemetry (Vib / Temp)', 355, eqTableY + 5);
      doc.text('Status', 480, eqTableY + 5);

      let eqY = eqTableY + 18;
      const displayEqs = equipments.length > 0 ? equipments.slice(0, 8) : [
        { name: 'Raw Water Intake Pump A', type: 'Intake Pump', healthScore: 92, vibration: 1.8, temperature: 48.2, status: 'OPERATIONAL' },
        { name: 'Flocculation Mixer 1', type: 'Rapid Mixer', healthScore: 95, vibration: 1.2, temperature: 42.5, status: 'OPERATIONAL' },
        { name: 'Chemical Dosing Pump B', type: 'Dosing Pump', healthScore: 88, vibration: 2.1, temperature: 51.0, status: 'OPERATIONAL' },
        { name: 'Backwash Water Pump', type: 'Sludge Pump', healthScore: 71, vibration: 5.8, temperature: 74.0, status: 'WARNING' },
        { name: 'High-Lift Service Pump 2', type: 'Distribution Pump', healthScore: 28, vibration: 12.4, temperature: 96.5, status: 'CRITICAL' }
      ];

      displayEqs.forEach((eq, i) => {
        if (eqY + 18 > 710) {
          doc.addPage();
          drawHeaderBanner();
          eqY = 70;
        }
        doc.rect(50, eqY, 512, 18).fill(i % 2 === 0 ? '#f8fafc' : '#ffffff');
        doc.fillColor('#1e293b').fontSize(8.5).font('Helvetica');
        doc.text((eq.name || '').substring(0, 24), 60, eqY + 5);
        doc.text(eq.type || 'Pump', 195, eqY + 5);
        doc.text(`${eq.healthScore || 90}%`, 275, eqY + 5);
        doc.text(`${eq.vibration || 1.5} mm/s | ${eq.temperature || 45}°C`, 355, eqY + 5);

        const statusColor = eq.status === 'CRITICAL' ? '#dc2626' : (eq.status === 'WARNING' ? '#d97706' : '#059669');
        doc.fillColor(statusColor).font('Helvetica-Bold').text(eq.status || 'OPERATIONAL', 480, eqY + 5);
        eqY += 18;
      });

      doc.y = eqY + 12;

      // 4. Incidents & Alert Logs
      checkPageBreak(110);
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('4. Incidents & Alarm Log Summary');
      doc.moveDown(0.3);

      doc.fillColor('#334155').fontSize(8.5).font('Helvetica')
         .text(`Total Alerts Recorded: ${reportData.alertsCount || 0}   |   Critical Anomalies: ${reportData.criticalCount || 0}   |   Warning Alerts: ${reportData.warningCount || 0}`);
      doc.moveDown(0.4);

      const alertTableY = doc.y;
      doc.rect(50, alertTableY, 512, 18).fill('#1e293b');
      doc.fillColor('#ffffff').fontSize(8.5).font('Helvetica-Bold');
      doc.text('Timestamp', 60, alertTableY + 5);
      doc.text('Severity', 160, alertTableY + 5);
      doc.text('Category', 235, alertTableY + 5);
      doc.text('Alarm Description', 330, alertTableY + 5);

      const alerts = reportData.alerts || [];
      const displayAlerts = alerts.length > 0 ? alerts.slice(0, 4) : [
        { timestamp: new Date(), severity: 'CRITICAL', type: 'EQUIPMENT_HEALTH', message: 'High-Lift Service Pump 2 temperature exceeded 95°C' },
        { timestamp: new Date(Date.now() - 3600000), severity: 'WARNING', type: 'THRESHOLD_EXCEEDED', message: 'Filter Bed 1 differential pressure high (5.8 mm/s)' }
      ];

      let alY = alertTableY + 18;
      displayAlerts.forEach((alt, i) => {
        if (alY + 18 > 710) {
          doc.addPage();
          drawHeaderBanner();
          alY = 70;
        }
        doc.rect(50, alY, 512, 18).fill(i % 2 === 0 ? '#f8fafc' : '#ffffff');
        doc.fillColor('#1e293b').fontSize(8).font('Helvetica');
        doc.text(new Date(alt.timestamp).toLocaleTimeString(), 60, alY + 5);
        
        const sevColor = alt.severity === 'CRITICAL' ? '#dc2626' : (alt.severity === 'WARNING' ? '#d97706' : '#2563eb');
        doc.fillColor(sevColor).font('Helvetica-Bold').text(alt.severity, 160, alY + 5);
        doc.fillColor('#1e293b').font('Helvetica').text(alt.type || 'ANOMALY', 235, alY + 5);
        doc.text((alt.message || '').substring(0, 38), 330, alY + 5);
        alY += 18;
      });

      doc.y = alY + 12;

      // 5. AI Chemical Optimization & Human Approval
      checkPageBreak(100);
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('5. AI Chemical Optimization & Operator Approval');
      doc.moveDown(0.3);

      const doseStats = reportData.doseStats || {};
      doc.fillColor('#334155').fontSize(9).font('Helvetica');
      doc.text(`• AI Recommendations Generated: ${doseStats.total || 12}`);
      doc.text(`• Human Operator Approvals / Adjustments: ${doseStats.approved || 11} (91.6% Verification Rate)`);
      doc.text(`• Estimated Chemical Cost Savings: ${doseStats.estimatedSavings || '14.5%'} vs static dosage baseline.`);
      doc.text(`• Optimized Dosage Targets: Coagulant (Alum) 24.5 mg/L, Chlorine Disinfectant 1.85 mg/L, pH Neutralizer 4.2 mg/L.`);
      doc.moveDown(1);

      // 6. Digital Twin Simulation & Predictive Analytics
      checkPageBreak(110);
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('6. Digital Twin Predictive Simulation Summary');
      doc.moveDown(0.3);

      const twin = reportData.digitalTwin || {};
      doc.fillColor('#334155').fontSize(9).font('Helvetica');
      doc.text(`• Raw Water Simulation Input: Turbidity = ${twin.inputParameters?.turbidity || 12.5} NTU | pH = ${twin.inputParameters?.pH || 7.8} | Flow = ${twin.inputParameters?.flow || 120} GPM`);
      doc.text(`• Optimized Chemical Addition: Chlorine Dose = ${twin.chemicalDose || 3.2} mg/L`);
      doc.text(`• Predicted Treated Effluent: Turbidity = ${twin.predictedOutput?.predictedTurbidity || 0.42} NTU | Chlorine = ${twin.predictedOutput?.predictedChlorine || 1.85} mg/L`);
      doc.text(`• Predicted Water Quality Score: ${twin.waterQualityScore || 95} / 100`);
      doc.text(`• Model Confidence Level: 96.8% (Physics-Informed Hybrid Model)`);
      doc.moveDown(1);

      // 7. Compliance & Operational Threshold Indicators
      checkPageBreak(130);
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('7. Compliance & Operational Threshold Indicators (EPA / WHO Standards)');
      doc.moveDown(0.3);

      const compTableY = doc.y;
      doc.rect(50, compTableY, 512, 18).fill('#1e293b');
      doc.fillColor('#ffffff').fontSize(8.5).font('Helvetica-Bold');
      doc.text('Regulated Parameter', 60, compTableY + 5);
      doc.text('EPA / WHO Standard', 210, compTableY + 5);
      doc.text('Plant Measured Value', 355, compTableY + 5);
      doc.text('Compliance Result', 470, compTableY + 5);

      const compRows = [
        { param: 'pH Level (Hydrogen Ion)', standard: '6.5 - 8.5 pH Units', measured: `${stats.phAvg || '7.35'} pH`, status: 'PASS' },
        { param: 'Turbidity (Effluent)', standard: '< 1.0 NTU (95% samples)', measured: `${stats.turbidityAvg || '0.45'} NTU`, status: 'PASS' },
        { param: 'Free Residual Chlorine', standard: '0.2 - 4.0 mg/L', measured: `${stats.chlorineAvg || '1.62'} mg/L`, status: 'PASS' },
        { param: 'Total Coliform Bacteria', standard: '0 CFU / 100 mL', measured: '0 CFU / 100 mL', status: 'PASS' },
        { param: 'Disinfection Byproducts (THMs)', standard: '< 80 µg/L', measured: '22 µg/L', status: 'PASS' }
      ];

      let cpY = compTableY + 18;
      compRows.forEach((cr, i) => {
        if (cpY + 18 > 710) {
          doc.addPage();
          drawHeaderBanner();
          cpY = 70;
        }
        doc.rect(50, cpY, 512, 18).fill(i % 2 === 0 ? '#f8fafc' : '#ffffff');
        doc.fillColor('#1e293b').fontSize(8.5).font('Helvetica');
        doc.text(cr.param, 60, cpY + 5);
        doc.text(cr.standard, 210, cpY + 5);
        doc.text(cr.measured, 355, cpY + 5);
        doc.fillColor('#059669').font('Helvetica-Bold').text(`${cr.status} [SIM]`, 470, cpY + 5);
        cpY += 18;
      });

      doc.y = cpY + 18;

      // Bottom disclaimer box
      checkPageBreak(45);
      doc.rect(50, doc.y, 512, 30).fill('#f1f5f9').stroke('#cbd5e1');
      doc.fillColor('#475569').fontSize(7.5).font('Helvetica-Oblique')
         .text('DISCLAIMER: This document was generated by AQUA-OPTIMA AI for academic prototype demonstration purposes. All metrics are synthesized from treatment plant simulation data.', 55, doc.y + 7, { width: 502, align: 'center' });

      doc.end();

      stream.on('finish', () => resolve(outputPath));
      stream.on('error', (err) => reject(err));
    } catch (err) {
      reject(err);
    }
  });
};

module.exports = { generateCompliancePDF };
