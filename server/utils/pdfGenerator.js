const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

const generateCompliancePDF = (reportData, outputPath) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 50 });
      const dir = path.dirname(outputPath);
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }

      const stream = fs.createWriteStream(outputPath);
      doc.pipe(stream);

      // Header
      doc.fontSize(20).fillColor('#1e40af').text('AI-POWERED WATER TREATMENT SYSTEM', { align: 'center' });
      doc.fontSize(14).fillColor('#374151').text('COMPLIANCE & AUDIT REPORT (PROTOTYPE DEMO)', { align: 'center' });
      doc.moveDown(1.5);

      // Report Metadata
      doc.fontSize(11).fillColor('#1f2937');
      doc.text(`Plant Name: ${reportData.plantName || 'Central Water Treatment Plant'}`);
      doc.text(`Report Period: ${new Date(reportData.periodStart).toLocaleDateString()} to ${new Date(reportData.periodEnd).toLocaleDateString()}`);
      doc.text(`Report Type: ${reportData.reportType || 'WEEKLY'}`);
      doc.text(`Generated By: ${reportData.generatedByName || 'System Administrator'}`);
      doc.text(`Generated On: ${new Date().toLocaleString()}`);
      doc.moveDown(1);
      doc.strokeColor('#e5e7eb').lineWidth(1).moveTo(50, doc.y).lineTo(550, doc.y).stroke();
      doc.moveDown(1);

      // Water Quality Summary
      doc.fontSize(14).fillColor('#1e40af').text('1. Water Quality & Sensor Summary');
      doc.fontSize(10).fillColor('#374151');
      doc.text(`• Average pH: ${reportData.stats?.phAvg || '7.2'} (Target: 6.5 - 8.5)`);
      doc.text(`• Average Turbidity: ${reportData.stats?.turbidityAvg || '1.8'} NTU (Target: < 5.0 NTU)`);
      doc.text(`• Average Residual Chlorine: ${reportData.stats?.chlorineAvg || '1.5'} mg/L (Target: 1.0 - 2.5 mg/L)`);
      doc.text(`• Average Flow Rate: ${reportData.stats?.flowAvg || '120'} GPM`);
      doc.text(`• System Water Quality Score: ${reportData.stats?.qualityScore || '92'}/100 [Simulated]`);
      doc.moveDown(1);

      // Alerts & Incidents Summary
      doc.fontSize(14).fillColor('#1e40af').text('2. Incidents & Alerts Overview');
      doc.fontSize(10).fillColor('#374151');
      doc.text(`• Total Active/Resolved Alerts in Period: ${reportData.alertsCount || 0}`);
      doc.text(`• Critical Anomalies Triggered: ${reportData.criticalCount || 0}`);
      doc.text(`• Compliance Status: MEETS DRINKING WATER STANDARDS (SIMULATED PROTOTYPE)`);
      doc.moveDown(1);

      // AI Chemical Dose & Human Approval Summary
      doc.fontSize(14).fillColor('#1e40af').text('3. AI Chemical Optimization & Human Approval');
      doc.fontSize(10).fillColor('#374151');
      doc.text(`• AI Dose Recommendations Issued: ${reportData.doseStats?.total || 0}`);
      doc.text(`• Operator Approvals / Adjustments: ${reportData.doseStats?.approved || 0}`);
      doc.text(`• Estimated Chemical Savings: ${reportData.doseStats?.estimatedSavings || '14.2%'} (Simulation baseline comparison)`);
      doc.moveDown(1.5);

      // Disclaimer Footer
      doc.fontSize(8).fillColor('#6b7280').text(
        'NOTICE: This document is an academic prototype demonstration generated by the AI-Powered Water Treatment System. All sensor values, scores, and chemical dose metrics are simulated demo values.',
        { align: 'center', italic: true }
      );

      doc.end();

      stream.on('finish', () => resolve(outputPath));
      stream.on('error', (err) => reject(err));
    } catch (err) {
      reject(err);
    }
  });
};

module.exports = { generateCompliancePDF };
